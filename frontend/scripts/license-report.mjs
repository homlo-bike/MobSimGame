#!/usr/bin/env node
// Writes the dependency licence report (production and development npm packages)
// with a licence-text link and the source repository URL for every package.
// Reads only package-lock.json and installed package.json files (no network).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Packages whose metadata is missing or wrong, reviewed by hand from their LICENSE file.
const MANUAL = {
  arc: {
    license: 'BSD-2-Clause',
    note: 'no licence field in package.json; BSD-style text in LICENSE.md, plus GDAL-LICENSE.md (MIT) for ported OGR code',
  },
  'splaytree-ts': {
    license: 'BSD-3-Clause',
    note: 'package.json says "BDS-3-Clause" (typo); LICENSE file is BSD 3-Clause',
  },
};
const MANUAL_REPOS = {
  quickselect: 'https://github.com/mourner/quickselect',
  'robust-predicates': 'https://github.com/mourner/robust-predicates',
};
// Platform-specific binary packages: only the one for the current OS is installed, so the
// others have no local package.json. Their source lives in the parent project's repository.
const PLATFORM_REPOS = [
  [/^@esbuild\//, 'https://github.com/evanw/esbuild'],
  [/^@rollup\/rollup-/, 'https://github.com/rollup/rollup'],
  [/^@tailwindcss\/oxide-/, 'https://github.com/tailwindlabs/tailwindcss'],
  [/^lightningcss-/, 'https://github.com/parcel-bundler/lightningcss'],
  [/^fsevents$/, 'https://github.com/fsevents/fsevents'],
];

function repoUrl(pkg) {
  let r = pkg.repository;
  if (r && typeof r === 'object') r = r.url;
  if (typeof r !== 'string' || !r) {
    return (
      pkg.homepage ?? MANUAL_REPOS[pkg.name] ?? PLATFORM_REPOS.find(([re]) => re.test(pkg.name))?.[1] ?? null
    );
  }
  r = r.trim();
  if (/^github:/.test(r)) r = r.replace(/^github:/, '');
  if (/^[\w.-]+\/[\w.-]+$/.test(r)) r = `https://github.com/${r}`;
  return r
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^ssh:\/\/git@/, 'https://')
    .replace(/^git@github\.com:/, 'https://github.com/')
    .replace(/\.git$/, '')
    .replace(/#.*$/, '');
}

function licenseLinks(expr) {
  const ids =
    String(expr)
      .match(/[A-Za-z0-9.+-]+/g)
      ?.filter((t) => !['OR', 'AND', 'WITH'].includes(t)) ?? [];
  return ids.map((id) => `[${id}](https://spdx.org/licenses/${id}.html)`).join(', ');
}

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const rows = { prod: [], dev: [] };
for (const [path, info] of Object.entries(lock.packages ?? {})) {
  if (!path) continue;
  const pkgFile = join(path, 'package.json');
  const pkg = existsSync(pkgFile) ? JSON.parse(readFileSync(pkgFile, 'utf8')) : {};
  const name = pkg.name ?? path.replace(/^.*node_modules\//, '');
  const manual = MANUAL[name];
  const license = manual?.license ?? info.license ?? pkg.license ?? 'UNKNOWN';
  (info.dev ? rows.dev : rows.prod).push({
    name,
    version: info.version ?? pkg.version,
    license,
    note: manual?.note ?? (existsSync(pkgFile) ? '' : 'platform-specific binary, not installed on this OS'),
    repo: repoUrl({ ...pkg, name }) ?? `https://www.npmjs.com/package/${name}`,
  });
}

const dedupe = (list) => {
  const seen = new Set();
  return list
    .sort((a, b) => a.name.localeCompare(b.name) || String(a.version).localeCompare(String(b.version)))
    .filter((r) => (seen.has(`${r.name}@${r.version}`) ? false : (seen.add(`${r.name}@${r.version}`), true)));
};
const table = (list) => [
  '| Package | Version | Licence | Repository | Note |',
  '| --- | --- | --- | --- | --- |',
  ...list.map((r) => `| ${r.name} | ${r.version} | ${licenseLinks(r.license)} | <${r.repo}> | ${r.note} |`),
];
const summary = (list) =>
  Object.entries(list.reduce((m, r) => ((m[r.license] = (m[r.license] ?? 0) + 1), m), {}))
    .sort()
    .map(([l, n]) => `- ${l}: ${n}`);

const prod = dedupe(rows.prod);
const dev = dedupe(rows.dev);
const out = [
  '# Frontend dependency licences',
  '',
  'Generated by `npm run licenses` (frontend/scripts/license-report.mjs) from package-lock.json.',
  'Re-run after every dependency change. Licence links point to the SPDX licence text; the',
  'licence file shipped with each package is in `node_modules/<package>/`.',
  '',
  'All licences below are compatible with the project licence, AGPL-3.0-only (see THIRD_PARTY_NOTICES.md).',
  '',
  `## Production dependencies (bundled into the web app): ${prod.length}`,
  '',
  ...summary(prod),
  '',
  ...table(prod),
  '',
  `## Development dependencies (build and test tools, not shipped): ${dev.length}`,
  '',
  ...summary(dev),
  '',
  ...table(dev),
  '',
].join('\n');
const target = process.argv[2] ?? '../docs/licenses/frontend-dependencies.md';
writeFileSync(target, out);
console.log(`Wrote ${prod.length} production and ${dev.length} development packages to ${target}`);
const unknown = [...prod, ...dev].filter((r) => r.license === 'UNKNOWN');
if (unknown.length) {
  console.error(`Packages without a licence: ${unknown.map((r) => r.name).join(', ')}`);
  process.exit(1);
}
