#!/usr/bin/env node
// Writes a dependency licence report for production npm dependencies (no network access needed).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
// Packages whose package.json has no licence field, reviewed by hand from their LICENSE file.
const MANUAL = { arc: 'BSD-style (no SPDX field; see node_modules/arc/LICENSE.md and GDAL-LICENSE.md)' };
const rows = [];
for (const [path, info] of Object.entries(lock.packages ?? {})) {
  if (!path || info.dev) continue;
  const pkgFile = join(path, 'package.json');
  let license = info.license;
  if (!license && existsSync(pkgFile)) license = JSON.parse(readFileSync(pkgFile, 'utf8')).license;
  const name = path.replace(/^.*node_modules\//, '');
  rows.push({ name, version: info.version, license: license ?? MANUAL[name] ?? 'UNKNOWN' });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const counts = rows.reduce((m, r) => ((m[r.license] = (m[r.license] ?? 0) + 1), m), {});
const out = [
  '# Frontend production dependency licences',
  '',
  'Generated by `npm run licenses` from package-lock.json. Re-run after dependency changes.',
  '',
  '## Summary',
  '',
  ...Object.entries(counts)
    .sort()
    .map(([l, n]) => `- ${l}: ${n}`),
  '',
  '## Packages',
  '',
  '| Package | Version | Licence |',
  '| --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
].join('\n');
const target = process.argv[2] ?? '../docs/licenses/frontend-dependencies.md';
writeFileSync(target, out);
console.log(`Wrote ${rows.length} packages to ${target}`);
for (const [l, n] of Object.entries(counts))
  if (/GPL|AGPL|UNKNOWN/.test(l)) console.log(`Note: ${n} package(s) under ${l}`);
