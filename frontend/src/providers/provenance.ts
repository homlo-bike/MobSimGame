import type { Provenance } from '../domain/schema';

export const OSM_ATTRIBUTION = '© OpenStreetMap contributors (ODbL)';
export const OSM_COPYRIGHT_URL = 'https://www.openstreetmap.org/copyright';

export function demoProvenance(dataset: string, extra: Partial<Provenance> = {}): Provenance {
  return {
    provider: 'MobSimGame demonstration provider',
    dataset,
    sourceUrl: null,
    license: 'MIT (synthetic data generated by MobSimGame)',
    attribution: 'Synthetic demonstration data, not a real place or measurement',
    retrievedAt: new Date().toISOString(),
    coverage: 'Anywhere (synthetic)',
    datasetDate: null,
    spatialResolution: null,
    status: 'demonstration',
    limitations: ['Synthetic values for demonstrating the interface. They describe no real place.'],
    cacheExpiresAt: null,
    confidence: 'unknown',
    ...extra,
  };
}

export function osmProvenance(extra: Partial<Provenance> = {}): Provenance {
  return {
    provider: 'OpenStreetMap via Overpass API (MobSimGame backend proxy)',
    dataset: 'OpenStreetMap',
    sourceUrl: OSM_COPYRIGHT_URL,
    license: 'ODbL-1.0',
    attribution: OSM_ATTRIBUTION,
    retrievedAt: new Date().toISOString(),
    coverage: 'Global, completeness varies by area',
    datasetDate: null,
    spatialResolution: null,
    status: 'observed',
    limitations: [
      'Volunteered data: a missing tag does not mean a feature does not exist.',
      'Completeness and currency vary by area.',
    ],
    cacheExpiresAt: null,
    confidence: 'medium',
    ...extra,
  };
}
